# funcion para cambiar el estado de una pqrs
def cambiar_estado(registro, nuevo_estado):
    """cambia el estado siguiendo el orden:
    registrada -> en proceso -> solucionada.
    al pasar a solucionada, guarda automaticamente la fecha de solucion.
    """
    estado_actual = obtener_dato(registro, "estado_peticion", estado_registrada)

    if estado_actual == estado_registrada and nuevo_estado == estado_en_proceso:
        if isinstance(registro, dict):
            registro["estado_peticion"] = nuevo_estado
        else:
            setattr(registro, "estado_peticion", nuevo_estado)
        print("estado cambiado a:", nuevo_estado)
        return True

    elif estado_actual == estado_en_proceso and nuevo_estado == estado_solucionada:
        if isinstance(registro, dict):
            registro["estado_peticion"] = nuevo_estado
            registro["fecha_solucion"] = date.today()
        else:
            setattr(registro, "estado_peticion", nuevo_estado)
            setattr(registro, "fecha_solucion", date.today())
        print("estado cambiado a:", nuevo_estado)
        print("fecha de solucion guardada")
        return True

    else:
        print("no se puede pasar de", estado_actual, "a", nuevo_estado)
        return False

